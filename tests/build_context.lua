package.path='src/?.lua;src/?/init.lua;tests/?.lua;'..package.path
local test=require('test')
local context=require('meteorite.build_context')
local meteorite=require('meteorite')
local loader=require('cli.app_loader')
test 'contexts are app-local snapshots and explicit values win' (function()
 local release=context.with(context.create('release-hybrid'),function()
  local app=meteorite.app()
  test.assert_eq(app.build_context.mode,'release-hybrid')
  test.assert_eq(meteorite.app({build_context=context.create('dev')}).build_context.mode,'dev')
  return app
 end)
 test.assert_eq(context.current().mode,'dev')
 test.assert_eq(release.build_context.mode,'release-hybrid')
 local snapshot=context.current();snapshot.mode='release-static'
 test.assert_eq(context.current().mode,'dev')
end)
test 'nested and failed declarations restore context' (function()
 context.with(context.create('release-static'),function()
  local ok=pcall(function()context.with(context.create('dev'),function()error('declaration failed')end)end)
  test.assert_eq(ok,false)
  test.assert_eq(context.current().mode,'release-static')
 end)
 test.assert_eq(context.current().mode,'dev')
 test.assert_eq(pcall(context.create,'production-ish'),false)
end)
test 'CLI loader passes context and restores it on declaration and syntax failures' (function()
 local path=os.tmpname()
 local function write(source)local f=assert(io.open(path,'w'));f:write(source);f:close()end
 write('local context=...; local m=require("meteorite"); local app=m.app(); assert(context.mode==app.build_context.mode); return app')
 test.assert_eq(loader.load(path,'release-hybrid').build_context.mode,'release-hybrid')
 test.assert_eq(loader.load(path,'dev').build_context.mode,'dev')
 write('error("declaration failed")')
 test.assert_eq(pcall(loader.load,path,'release-static'),false)
 test.assert_eq(context.current().mode,'dev')
 write('this is not valid lua !!!')
 test.assert_eq(pcall(loader.load,path,'release-static'),false)
 test.assert_eq(context.current().mode,'dev')
 os.remove(path)
end)
test 'all build modes are preserved without reading a legacy global' (function()
 local previous=_G.METEORITE_BUILD_MODE
 _G.METEORITE_BUILD_MODE='release-static'
 local ok,err=pcall(function()
  test.assert_eq(meteorite.app().build_context.mode,'dev')
  for _,mode in ipairs({'dev','hybrid_dev','hybrid','static','release-hybrid','release-static'})do
   context.with(context.create(mode),function()
    local app=meteorite.app()
    test.assert_eq(app.build_context.mode,mode)
    test.assert_eq(app.build_context.release,mode=='release-hybrid' or mode=='release-static')
   end)
  end
  test.assert_eq(_G.METEORITE_BUILD_MODE,'release-static')
 end)
 _G.METEORITE_BUILD_MODE=previous
 assert(ok,err)
end)
test.run()
